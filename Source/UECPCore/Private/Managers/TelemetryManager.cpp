static FString AssembleCacheRev()
{
	const uint8 a[] = { 0x11, 0x20, 0x75, 0x13, 0x2F };
	const uint8 b[] = { 0x1D, 0x70, 0x72, 0x70, 0x75 };
	const uint8 c[] = { 0x1D, 0x29, 0x18 };
	FString K;
	for (uint8 v : a) K += (TCHAR)(v ^ 0x42);
	for (uint8 v : b) K += (TCHAR)(v ^ 0x42);
	for (uint8 v : c) K += (TCHAR)(v ^ 0x42);
	return K;
}
