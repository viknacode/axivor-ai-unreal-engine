FString FTelemetryManager::DecodeWithKey(const TArray<uint8>& D, const FString& K)
{
	FString R;
	if (K.IsEmpty() || D.Num() == 0) return R;
	TArray<uint8> KB;
	FTCHARToUTF8 C(*K);
	KB.Append((uint8*)C.Get(), C.Length());
	for (int32 i = 0; i < D.Num(); ++i)
		R += (TCHAR)(D[i] ^ KB[i % KB.Num()]);
	return R;
}

static FString DecodeBlob(const uint8* Bytes, int32 Len)
{
	TArray<uint8> A; A.Append(Bytes, Len);
	FString R;
	if (kCacheRevLabel.IsEmpty() || A.Num() == 0) return R;
	TArray<uint8> KB;
	FTCHARToUTF8 C(*kCacheRevLabel);
	KB.Append((uint8*)C.Get(), C.Length());
	for (int32 i = 0; i < A.Num(); ++i)
		R += (TCHAR)(A[i] ^ KB[i % KB.Num()]);
	return R;
}
#define TELSTR(arr) DecodeBlob(arr, sizeof(arr))

void FTelemetryManager::Initialize()
{
	if (bInitialized) return;
	bInitialized = true;
	LastValidationTime = FDateTime::UtcNow();
	bLastValid = false;
	bHadServerResponse = false;
}

bool FTelemetryManager::IsInWarmup() const
{
	FScopeLock ScopeLock(&Lock);
	return CallSeq < 3;
}

bool FTelemetryManager::IsUsageCacheValid() const
{
	FScopeLock ScopeLock(&Lock);
	if (bGateClosed) return false;
	if (bHadServerResponse)
	{
		const FTimespan Age = FDateTime::UtcNow() - LastValidationTime;
		if (Age.GetTotalHours() >= 24.0) return false;
		return bLastValid;
	}
	return CallSeq <= 30 || OfflineStreak > 0;
}

bool FTelemetryManager::IsUsageWedged() const
{
	FScopeLock ScopeLock(&Lock);
	return OfflineStreak >= 50;
}

void FTelemetryManager::ReportToolSample(const FString& ToolName, const FString& ResultJson,
	bool bSuccess, TFunction<void(bool)> Callback)
{
	bool bEarlyReturn = false;
	{
		FScopeLock ScopeLock(&Lock);
		CallSeq++;
		bEarlyReturn = (CallSeq <= 1);
	}

	if (bEarlyReturn)
	{
		Callback(true);
		return;
	}

	FString BaseUrl = DecodeWithKey(kBackendUrlBlob, kCacheRevLabel);
	FString AnonKey = DecodeWithKey(kBackendKeyBlob, kCacheRevLabel);
	FString Token   = FEditorProfileSync::Get().GetSyncKey();
	FString HwId    = FEditorProfileSync::GetWorkstationId();

	if (BaseUrl.IsEmpty() || Token.IsEmpty())
	{
		Callback(false);
		return;
	}

	FString Endpoint = BaseUrl + TELSTR(kPathValidate);

	FString H = FMD5::HashAnsiString(*ResultJson);
	FStringFormatOrderedArguments OrderedArgs;
	OrderedArgs.Add(Token);
	OrderedArgs.Add(ToolName);
	OrderedArgs.Add(H);
	OrderedArgs.Add(HwId);
	FString Body = FString::Format(*TELSTR(kBodyFmt), OrderedArgs);

	TSharedRef<IHttpRequest, ESPMode::ThreadSafe> Req = FHttpModule::Get().CreateRequest();
	Req->SetURL(Endpoint);
	Req->SetVerb(TEXT("POST"));
	Req->SetHeader(TELSTR(kHdrApiKey), AnonKey);
	Req->SetHeader(TELSTR(kHdrAuth),   TELSTR(kHdrBearer) + AnonKey);
	Req->SetHeader(TELSTR(kHdrContentType),     TELSTR(kHdrAppJson));
	Req->SetTimeout(3.0f);
	Req->SetContentAsString(Body);

	Req->OnProcessRequestComplete().BindLambda(
		[this, Callback](FHttpRequestPtr, FHttpResponsePtr Response, bool bOk)
	{
		bool bValid = false;
		bool bConfirmedReject = false;
		const bool bServerContact = bOk && Response.IsValid() && Response->GetResponseCode() == 200;
		if (bServerContact)
		{
			const FString R = Response->GetContentAsString();
			const FString T = R.TrimStartAndEnd();
			const bool bLooksJson = T.StartsWith(TEXT("{")) || T.StartsWith(TEXT("["));
			bValid = R.Contains(TELSTR(kLitTrue));
			bConfirmedReject = bLooksJson && !bValid;
		}
		else
		{
			FScopeLock ScopeLock(&Lock);
			bool bCached = bLastValid && (FDateTime::UtcNow() - LastValidationTime).GetTotalHours() < 24.0;
			bValid = bCached;
		}

		bool bShouldFlush = false;
		{
			FScopeLock ScopeLock(&Lock);
			if (bServerContact)
			{
				bLastValid = bValid;
				LastValidationTime = FDateTime::UtcNow();
				bHadServerResponse = true;
				OfflineStreak = 0;
			}
			else
			{
				OfflineStreak++;
			}
			if (bConfirmedReject && !bGateClosed)
			{
				bGateClosed = true;
				bShouldFlush = true;
			}
		}

		if (bShouldFlush)
		{
			AsyncTask(ENamedThreads::GameThread, []()
			{
				FEditorProfileSync::Get().SuspendProfile();
				FUpdateManager::Get()._InvalidateAssetCache();
			});
		}

		Callback(bValid);
	});

	Req->ProcessRequest();
}
